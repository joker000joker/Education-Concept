-- =============================================================================
-- SECTIONAL TEST RESULTS SCHEMA FOR SUPABASE
-- Education Concept Sectional Test "Latest Attempt" Architecture
-- =============================================================================

-- 1. Create sectional_test_results table
CREATE TABLE IF NOT EXISTS sectional_test_results (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  test_id BIGINT NOT NULL REFERENCES sectional_tests(id) ON DELETE CASCADE,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  score NUMERIC NOT NULL DEFAULT 0,
  total_marks NUMERIC NOT NULL DEFAULT 50,
  correct_answers INTEGER NOT NULL DEFAULT 0,
  incorrect_answers INTEGER NOT NULL DEFAULT 0,
  unattempted_answers INTEGER NOT NULL DEFAULT 0,
  accuracy NUMERIC NOT NULL DEFAULT 0,
  negative_marks NUMERIC NOT NULL DEFAULT 0,
  time_taken_seconds INTEGER NOT NULL DEFAULT 0,
  answers JSONB NOT NULL DEFAULT '{}'::jsonb,
  completed_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  -- CRITICAL: Unique constraint ensures ONE stored latest result per student per test
  CONSTRAINT uq_sectional_test_user UNIQUE (test_id, user_id)
);

-- Indexes for performance
CREATE INDEX IF NOT EXISTS idx_sec_test_results_user ON sectional_test_results(user_id);
CREATE INDEX IF NOT EXISTS idx_sec_test_results_test ON sectional_test_results(test_id);

-- 2. Row Level Security (RLS)
ALTER TABLE sectional_test_results ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Users select own sectional_test_results" ON sectional_test_results;
DROP POLICY IF EXISTS "Users insert own sectional_test_results" ON sectional_test_results;
DROP POLICY IF EXISTS "Users update own sectional_test_results" ON sectional_test_results;
DROP POLICY IF EXISTS "Admin delete sectional_test_results" ON sectional_test_results;

-- Students can read only their own results; Admins can read all results
CREATE POLICY "Users select own sectional_test_results" ON sectional_test_results
  FOR SELECT USING (auth.uid() = user_id OR public.is_admin());

-- Students can insert only their own results
CREATE POLICY "Users insert own sectional_test_results" ON sectional_test_results
  FOR INSERT WITH CHECK (auth.uid() = user_id);

-- Students can update only their own results (upon reattempt)
CREATE POLICY "Users update own sectional_test_results" ON sectional_test_results
  FOR UPDATE USING (auth.uid() = user_id);

-- Admins can delete results if needed
CREATE POLICY "Admin delete sectional_test_results" ON sectional_test_results
  FOR DELETE USING (public.is_admin());

-- 3. Auto-update timestamps trigger
CREATE OR REPLACE FUNCTION update_sectional_results_modified_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ language 'plpgsql';

DROP TRIGGER IF EXISTS update_sectional_test_results_modtime ON sectional_test_results;
CREATE TRIGGER update_sectional_test_results_modtime
  BEFORE UPDATE ON sectional_test_results
  FOR EACH ROW EXECUTE FUNCTION update_sectional_results_modified_column();
