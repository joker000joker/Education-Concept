-- 2. MODIFIED TIMESTAMP TRIGGERS

CREATE OR REPLACE FUNCTION update_phase_a_modified_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ language 'plpgsql';

DO $$
DECLARE
    t text;
BEGIN
    FOR t IN SELECT unnest(ARRAY['paid_ebooks', 'free_ebooks', 'current_affairs', 'exam_patterns', 'study_resources', 'banners', 'top_recommendations', 'app_settings'])
    LOOP
        EXECUTE format('
            DROP TRIGGER IF EXISTS update_%I_modtime ON %I;
            CREATE TRIGGER update_%I_modtime
            BEFORE UPDATE ON %I
            FOR EACH ROW EXECUTE FUNCTION update_phase_a_modified_column();
        ', t, t, t, t);
    END LOOP;
END;
$$;

