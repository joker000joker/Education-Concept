-- 4. APPLY RLS POLICIES

-- PAID EBOOKS
DROP POLICY IF EXISTS "Public select paid_ebooks" ON paid_ebooks;
DROP POLICY IF EXISTS "Admin insert paid_ebooks" ON paid_ebooks;
DROP POLICY IF EXISTS "Admin update paid_ebooks" ON paid_ebooks;
DROP POLICY IF EXISTS "Admin delete paid_ebooks" ON paid_ebooks;
CREATE POLICY "Public select paid_ebooks" ON paid_ebooks FOR SELECT USING (published = true OR public.is_admin());
CREATE POLICY "Admin insert paid_ebooks" ON paid_ebooks FOR INSERT WITH CHECK (public.is_admin());
CREATE POLICY "Admin update paid_ebooks" ON paid_ebooks FOR UPDATE USING (public.is_admin());
